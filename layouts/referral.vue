<script>
import { mapGetters, mapMutations, mapActions } from "vuex";

export default {
	data() {
		return {
			// referralPages:["Home","Rewards","Track Progress", "FAQs"]
			referralPages: [
				{
					text: "Home",
					route: "/referral",
				},
				{
					text: "Rewards",
					route: "/referral/rewards",
				},
				{
					text: "Track Progress",
					route: "/referral/progress",
				},
				{
					text: "FAQs",
					route: "/referral/faq",
				},
			],
			referralEmail: "",
			rewardsSuccessPopupState: false,
			generatedURL: "",
			succesfulCopyToastState: false,
		};
	},
	computed: {
		...mapGetters("Referral", [
			"referralPopup",
			"errorMessageState",
			"errorMessage",
			"loadingAnimationState",
		]),
	},
	methods: {
		...mapMutations("Referral", [
			"referralPopupToggle",
			"showReferralPopupErrorMessage",
			"showLoadingAnimation",
			"hideLoadingAnimation",
		]),
		...mapActions("Referral", [
			"sendReferralThroughEmail",
			"getReferralURL",
		]),
		sendReferral() {
			const reg = /^\S+@\S+\.\S+$/;
			if (
				String(this.referralEmail)
					.toLowerCase()
					.match(reg) &&
				this.referralEmail
			) {
				this.showLoadingAnimation();
				this.sendReferralThroughEmail(this.referralEmail).then(res => {
					this.hideLoadingAnimation();
					if (res.ok) {
						// alert("Referred successfully");
						this.referralPopupToggle();
						this.rewardsSuccessPopupState = true;
						this.$router.push("/referral/progress");
						if (window.analytics) {
							window.analytics.track(
								"referral_invite_sent",
								{
									name: "Referral invite sent",
									event_category: "Refferal Strategy",
								},
								{
									integrations: {
										Amplitude: {
											session_id: new Date().getTime(),
										},
									},
								},
								{ timestamp: new Date().getTime() }
							);
						}
					} else {
						if (res.data.error.error) {
							this.showReferralPopupErrorMessage(
								res.data.error.error
							);
						}
					}
				});
				this.referralEmail = "";
			} else {
				this.showReferralPopupErrorMessage(
					"Enter a valid email address"
				);
				// alert('Enter an valid email first')
			}
		},
		closeRewardsPopup() {
			this.rewardsSuccessPopupState = false;
		},
		onReferNowButtonClick() {
			this.referralPopupToggle();
			if (window.analytics) {
				window.analytics.track(
					"click_refer_now",
					{
						name: "Click Refer now",
						event_category: "Refferal Strategy",
					},
					{
						integrations: {
							Amplitude: { session_id: new Date().getTime() },
						},
					},
					{ timestamp: new Date().getTime() }
				);
			}
		},
		onGenerateLinkButtonClick() {
			// Call the API call here to generate the link
			window.analytics.track(
				"refferal_link_generated",
				{
					action: "click",
					name: "Generated Link",
					event_category: "Refferal",
					event_label: "Generated Link",
				},
				{
					integrations: {
						Amplitude: { session_id: new Date().getTime() },
					},
				},
				{ timestamp: new Date().getTime() }
			);

			this.getReferralURL().then(data => {
				if (data.ok) {
					this.generatedURL = data.data;
					// console.log(this.generatedURL);
				}
			});
		},
		onReferralPopupCloseButtonClick() {
			this.generatedURL = "";
			this.referralPopupToggle();
		},
		onCopyGeneratedURL() {
			try {
				navigator.clipboard.writeText(this.generatedURL).then(() => {
					this.succesfulCopyToastState = true;
					setTimeout(() => {
						this.succesfulCopyToastState = false;
					}, 1000);
				});
			} catch (err) {
				console.error("Failed to copy: ", err);
			}
		},
	},
};
</script>


